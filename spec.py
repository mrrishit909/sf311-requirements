"""Step 5: build the requirements document and traceability matrix from requirements.yaml, checking every cited number.

    ./venv/bin/python spec.py     -> docs/requirements.md, results/traceability.csv
"""
import re
from pathlib import Path

import pandas as pd
import yaml

HERE = Path(__file__).parent
R = HERE / "results"


def lookup(ev):
    """The value of `column` in the one row of results/<file> that matches `where`."""
    df = pd.read_csv(R / ev["file"], dtype=str)
    for k, v in ev["where"].items():
        df = df[df[k] == str(v)]
    assert len(df) == 1, (ev, len(df))
    return float(df[ev["column"]].iloc[0])


def numbers(text):
    """Counts (100 and up) and one-decimal percentages written in prose, e.g. '70,526' or '43.1%'."""
    found = [float(n.replace(",", "")) for n in re.findall(r"(?<![\w.-])(\d{1,3}(?:,\d{3})+|\d{3,}|\d+\.\d+)(?![\w-])", text)]
    return [n for n in found if n >= 100 or n != int(n)]


def validate(spec):
    """Every evidence value matches its results file; every number in a problem or a baseline is one of them (or a sum)."""
    for item in spec["requirements"] + spec["rejected"]:
        assert item["evidence"], item["id"]
        vals = []
        for ev in item["evidence"]:
            got = lookup(ev)
            assert abs(got - ev["value"]) < 1e-9, (item["id"], ev, got)
            vals.append(got)
        by_col = {}
        for ev, v in zip(item["evidence"], vals):
            by_col.setdefault(ev["column"], []).append(v)
        allowed = set(vals) | {sum(v) for v in by_col.values()}
        text = item.get("problem", item.get("reason", "")) + " " + " ".join(re.findall(r"baseline ([\d,.]+)", item.get("target", "")))
        for n in numbers(text):
            assert any(abs(n - a) < 1e-9 for a in allowed), (item["id"], n)
    for req in spec["requirements"]:
        assert req["priority"] in ("Must", "Should", "Could"), req["id"]
        for a in req["acceptance"]:                          # testable: a Given/When/Then scenario or a measured threshold
            assert re.match(r"Given .+, (when|then) .+", a) or re.search(r"\d", a), (req["id"], a)
        assert any(re.search(r"\d", a) for a in req["acceptance"]), (req["id"], "no measurable criterion")


def main():
    spec = yaml.safe_load((HERE / "requirements.yaml").read_text())
    validate(spec)
    rows, md = [], ["# SF 311 intake: requirements from a year of cases", "",
                    "Generated by `spec.py` from `requirements.yaml`. Baselines: 12 months of cases requested Sep 2025 - Aug 2026.",
                    "Targets are proposals for the service owners to agree.", ""]
    for req in spec["requirements"]:
        md += [f"## {req['id']} {req['title']}", "",
               f"**Type:** {req['type']} · **Priority:** {req['priority']} · **Stakeholders:** {', '.join(req['stakeholders'])}", "",
               f"**Problem.** {req['problem']}", "", f"**Requirement.** {req['statement']}", "", "**Acceptance criteria**", ""]
        md += [f"- {a}" for a in req["acceptance"]]
        md += ["", f"**Target (proposed).** {req['target']}", "", "**Evidence**", ""]
        for ev in req["evidence"]:
            where = ", ".join(f"{k} = {v}" for k, v in ev["where"].items()) or "the only row"
            md.append(f"- `results/{ev['file']}` ({where}): {ev['column']} = {ev['value']:g}")
            rows.append({"requirement": req["id"], "priority": req["priority"], "type": req["type"], "evidence_file": ev["file"],
                         "row": where, "column": ev["column"], "value": ev["value"],
                         "acceptance_criteria": len(req["acceptance"])})
        md.append("")
    md += ["## Considered and rejected", ""]
    for rej in spec["rejected"]:
        md += [f"- **{rej['id']} {rej['title']}.** {rej['reason']}"]
    (HERE / "docs").mkdir(exist_ok=True)
    (HERE / "docs" / "requirements.md").write_text("\n".join(md) + "\n")
    pd.DataFrame(rows).to_csv(R / "traceability.csv", index=False)
    print(f"{len(spec['requirements'])} requirements, {len(spec['rejected'])} rejected, {len(rows)} evidence links: all match")


if __name__ == "__main__":
    main()
